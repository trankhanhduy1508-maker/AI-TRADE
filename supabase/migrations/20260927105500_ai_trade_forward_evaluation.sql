create table if not exists ai_trade.forward_evaluation_snapshots (
  id bigint generated by default as identity primary key,
  strategy_id text not null,
  evaluation_state text not null check (evaluation_state in ('COLLECTING','FORWARD_REJECT','FORWARD_CANDIDATE')),
  closed_trades integer not null default 0,
  elapsed_days integer not null default 0,
  markets_with_trades integer not null default 0,
  positive_markets integer not null default 0,
  net_r_10bps numeric not null default 0,
  expectancy_r_10bps numeric not null default 0,
  profit_factor_r_10bps numeric,
  max_drawdown_r_10bps numeric not null default 0,
  return_to_drawdown_10bps numeric,
  net_r_20bps numeric not null default 0,
  market_positive_contribution_dominance numeric,
  flagged_bars integer not null default 0,
  entry_without_visible_stop integer not null default 0,
  gates jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists forward_evaluation_strategy_created_idx
  on ai_trade.forward_evaluation_snapshots(strategy_id,created_at desc);

revoke all on ai_trade.forward_evaluation_snapshots from anon, authenticated;

